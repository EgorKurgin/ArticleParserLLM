function build_summarize_prompt(article::Article)
    return """
Ты — научный ассистент физика-исследователя. Ниже — abstract научной статьи с arXiv.

Title: $(article.title)
Abstract: $(article.abstract)

Сделай максимально подробный пересказ этой статьи на русском языке (400–700 слов).
Исследователь работает над темами: **квантовые точки, открытые квантовые системы,
проблема измерения в квантовой механике**. Он хочет извлечь из статьи всё, что может
помочь в его исследованиях, независимо от того, теория это или эксперимент.

Структура ответа:

1. **О чём статья** — одно-два предложения, суть работы.

2. **Контекст и задача** — какую проблему решает автор, почему это важно.

3. **Методы и подход** — теоретический формализм, экспериментальная установка,
   численные методы — всё, что явно указано. Если используются конкретные уравнения,
   модели (например, Lindblad, Redfield, master equations, SSH-модель, формализм
   открытых систем, операторы измерения и т.д.) — назови их.

4. **Математический аппарат** — выпиши ключевые формулы, гамильтонианы, операторы,
   величины и обозначения, если они есть в abstract. Не выдумывай формулы,
   которых нет, но если в тексте упоминается какое-то уравнение или выражение —
   передай его точно.

5. **Результаты** — что конкретно получено. Числа, пределы, фазовые диаграммы,
   наблюдаемые эффекты.

6. **Связь с интересами исследователя** — явно укажи, чем эта работа может быть
   полезна для исследований по квантовым точкам, открытым квантовым системам
   или проблеме измерения. Если связи нет — прямо скажи об этом.

7. **Ограничения и открытые вопросы** — что не решено, где применимость ограничена,
   если это упоминается.

Правила:
- Пиши связным текстом, но с явными заголовками пунктов.
- Используй научный стиль, понятный физику.
- **Не выдумывай** детали, формулы или результаты, которых нет в abstract.
  Если какого-то пункта в тексте нет — напиши «в abstract не указано».
- Точность важнее красоты формулировок.
- Если в abstract есть нетривиальные термины, дай их на русском и в скобках на английском.
"""
end

function summarize(article::Article; kwargs...)
    prompt = build_summarize_prompt(article)
    raw = ollama_generate(prompt;
                          temperature=0.5,   # небольшая вариативность для естественности
                          num_predict=2000,   # ~500 слов русского текста
                          kwargs...)
    return String(strip(raw))
end